#!/usr/bin/env python3
"""Writes the macOS app's engine loader from the engine's C facade header.

The app loads the engine at launch, from a library that can be replaced by an update (see docs/updates.md).
For every function the header declares, the loader gets a pointer, which kl_engine_load() fills in from the loaded
library, and a stub with the same name that forwards to that pointer. The Swift code calls the stubs, so it does
not change when the engine does.

  gen_engine_loader.py           write apps/macos/Sources/CKettleLogic/engine_loader.c
  gen_engine_loader.py --check   fail if that file is out of date (used by ctest)
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
HEADER = ROOT / "core/include/kettlelogic/c/kettlelogic.h"
OUTPUT = ROOT / "apps/macos/Sources/CKettleLogic/engine_loader.c"

# A facade declaration: a return type, the name (which starts with kl_), and the parameter list. Nothing in the
# return type can be a brace, a parenthesis, or a semicolon, so a match never reaches past the previous declaration.
DECLARATION = re.compile(r"(?P<ret>[^;{}()]*?)\b(?P<name>kl_\w+)\s*\((?P<params>[^()]*)\)\s*;")


def without_comments_and_directives(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return "\n".join(line for line in text.splitlines() if not line.lstrip().startswith("#"))


def declarations(text):
    for match in DECLARATION.finditer(without_comments_and_directives(text)):
        ret = " ".join(match["ret"].split())
        params = " ".join(match["params"].split())
        yield ret, match["name"], params


def argument_names(params):
    if params in ("", "void"):
        return []
    names = []
    for param in params.split(","):
        found = re.search(r"(\w+)\s*$", param.strip())
        if not found:
            raise SystemExit(f"gen_engine_loader: cannot read the parameter name in '{param.strip()}'")
        names.append(found.group(1))
    return names


def render(header_text):
    found = list(declarations(header_text))
    names = [name for _, name, _ in found]
    if "kl_engine_abi_version" not in names:
        raise SystemExit("gen_engine_loader: the header must declare kl_engine_abi_version")

    out = []
    out.append("/* Generated by core/tools/gen_engine_loader.py from core/include/kettlelogic/c/kettlelogic.h.")
    out.append(" * Do not edit by hand. Run the script to regenerate it. */")
    out.append("")
    out.append("#include <dlfcn.h>")
    out.append("#include <stdio.h>")
    out.append("#include <stdlib.h>")
    out.append("#include <string.h>")
    out.append("")
    out.append("#include <kettlelogic/c/kettlelogic.h>")
    out.append('#include "engine_loader.h"')
    out.append("")
    out.append("/* The engine library, once loaded. Nothing else is needed from it: the pointers below are the only way in. */")
    out.append("static void *kl_engine_handle = NULL;")
    out.append("")
    out.append("/* A pointer type and a pointer for each function, filled in by kl_engine_load(). */")
    for ret, name, params in found:
        signature = params if params else "void"
        out.append(f"typedef {ret} (*kl_fn_{name})({signature});")
        out.append(f"static kl_fn_{name} kl_fp_{name} = NULL;")
    out.append("")
    out.append("static void kl_clear_pointers(void) {")
    for _, name, _ in found:
        out.append(f"    kl_fp_{name} = NULL;")
    out.append("}")
    out.append("")
    out.append("static void kl_set_error(char **error, const char *message) {")
    out.append("    if (error) {")
    out.append("        *error = strdup(message);")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("/* Unloads what was loaded, so a failed load leaves no pointer behind. */")
    out.append("static int kl_fail(void *handle, const char *message, char **error) {")
    out.append("    kl_clear_pointers();")
    out.append("    dlclose(handle);")
    out.append("    kl_set_error(error, message);")
    out.append("    return -1;")
    out.append("}")
    out.append("")
    out.append("static int kl_fail_missing(void *handle, const char *name, char **error) {")
    out.append("    char message[256];")
    out.append('    snprintf(message, sizeof message, "the engine does not export %s", name);')
    out.append("    return kl_fail(handle, message, error);")
    out.append("}")
    out.append("")
    out.append("#define KL_RESOLVE(name) \\")
    out.append("    if (!(kl_fp_##name = (kl_fn_##name)dlsym(handle, #name))) return kl_fail_missing(handle, #name, error)")
    out.append("")
    out.append("static void kl_engine_missing(const char *name) {")
    out.append('    fprintf(stderr, "Kettle Logic: %s was called before the engine was loaded\\n", name);')
    out.append("    abort();")
    out.append("}")
    out.append("")
    out.append("#define KL_REQUIRE(pointer, name) \\")
    out.append("    do { if (!(pointer)) kl_engine_missing(name); } while (0)")
    out.append("")
    out.append("int kl_engine_load(const char *path, char **error) {")
    out.append("    if (kl_engine_handle) {")
    out.append('        kl_set_error(error, "an engine is already loaded");')
    out.append("        return -1;")
    out.append("    }")
    out.append("    void *handle = dlopen(path, RTLD_NOW | RTLD_LOCAL);")
    out.append("    if (!handle) {")
    out.append("        const char *reason = dlerror();")
    out.append('        kl_set_error(error, reason ? reason : "the engine could not be loaded");')
    out.append("        return -1;")
    out.append("    }")
    out.append("    kl_fn_kl_engine_abi_version abi = (kl_fn_kl_engine_abi_version)dlsym(handle, \"kl_engine_abi_version\");")
    out.append("    if (!abi) {")
    out.append('        return kl_fail(handle, "the library is not a Kettle Logic engine", error);')
    out.append("    }")
    out.append("    int found = abi();")
    out.append("    if (found != KL_ENGINE_ABI_VERSION) {")
    out.append("        char message[256];")
    out.append("        snprintf(message, sizeof message,")
    out.append('                 "the engine has interface version %d, and this app needs %d",')
    out.append("                 found, KL_ENGINE_ABI_VERSION);")
    out.append("        return kl_fail(handle, message, error);")
    out.append("    }")
    out.append("    kl_clear_pointers();")
    for _, name, _ in found:
        out.append(f"    KL_RESOLVE({name});")
    out.append("    kl_engine_handle = handle;")
    out.append("    return 0;")
    out.append("}")
    out.append("")
    for ret, name, params in found:
        signature = params if params else "void"
        args = ", ".join(argument_names(params))
        call = f"kl_fp_{name}({args})"
        body = f"    return {call};" if ret != "void" else f"    {call};"
        out.append(f"{ret} {name}({signature}) {{")
        out.append(f'    KL_REQUIRE(kl_fp_{name}, "{name}");')
        out.append(body)
        out.append("}")
        out.append("")
    out.append("/* The engine in the build folder, for a run without an app bundle. Package.swift defines the path. */")
    out.append("const char *kl_build_engine_path(void) {")
    out.append("#ifdef KETTLELOGIC_BUILD_ENGINE")
    out.append("    return KETTLELOGIC_BUILD_ENGINE;")
    out.append("#else")
    out.append("    return NULL;")
    out.append("#endif")
    out.append("}")
    out.append("")
    return "\n".join(out) + "\n"


def main(argv):
    text = render(HEADER.read_text())
    if "--check" in argv:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT} is out of date. Run core/tools/gen_engine_loader.py.", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text)
    print(f"Wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
