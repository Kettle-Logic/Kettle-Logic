FermentableTemplate malt(const char* name, const char* group, const char* yieldSG, const char* colorSRM) {
    return {name, group, "grain", yieldSG, colorSRM};
}

CultureTemplate yeast(const char* name, const char* group, const char* type,
                      std::optional<std::string> attenuation = std::nullopt) {
    return {name, group, type, "dry", std::move(attenuation)};
}

CultureTemplate liquid(const char* name, const char* group, const char* type) {
    return {name, group, type, "liquid", std::nullopt};
}

